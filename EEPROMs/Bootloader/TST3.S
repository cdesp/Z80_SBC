
INCLUDE .\Bin\BOOTLD.SYM

FILEBUFFER EQU $F1F7
TEMPSAVE EQU $F12B
FINDSECTION EQU $07EB
COPYOSFILE1 EQU $06CA
SELECTED EQU $F12E
ROMSSEC	 EQU $F24E
MENU EQU $F12F
MNUCNT EQU $F12D

ORG $6000

LD HL, FILEBUFFER
LD B,200
AGN1:
LD A,(HL)
CALL RS_TX
INC HL
DJNZ AGN1

LD B,13
LD HL,$F12F		;MENU
CALL PRN

OUT1:

		LD A,(TEMPSAVE)
		LD H,A
		LD A,(TEMPSAVE+1)
		LD L,A

LD B,13
CALL PRN

;LD A,2
;LD (SELECTED),A

LD A,(MNUCNT)
CALL SOUTAS

LD A,(SELECTED)
CALL SOUTAS

;CALL GETSEL
LD B,13
LD HL,MENU
DEC HL
CALL PRN

LD A,10
CALL RS_TX
LD A,13
CALL RS_TX

JP BOOTMENU


PRN:
NXTC: LD A,(HL)
OR A
RET Z
CALL RS_TX
INC HL
DJNZ NXTC
RET

GETSEL:	LD A,(TEMPSAVE)
		LD H,A
		LD A,(TEMPSAVE+1)
		LD L,A				;HL TO BOOT.INI [ROMS]
		CALL FINDSECTION
		DEFM "ROMS"
		DB 0
		JR NC, ROM_NXT1
		CALL OS_PRNMSGSCR
		DEFM "ERROR [ROMS] NOT FOUND"
		DB 13,10,0
		JP BOOTMENU	
ROM_NXT1:	LD B,$FF
ROM_NXT2:	INC B
		LD DE,MENU			;NOT NEEDED ANYMORE			
		CALL COPYOSFILE1		;GET ALINE
		INC HL				;skip $0D
		INC HL				;skip $0A
		LD A,(SELECTED)
		CP B 
		JR NZ, ROM_NXT2
		
		LD HL,MENU			;ZT STRING OF THE INI FILE TO LOAD
		DEC HL
		LD A,'\'
		LD (HL),A
		CALL RS_TXT
		RET	




