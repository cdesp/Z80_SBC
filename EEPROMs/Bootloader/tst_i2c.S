INCLUDE .\BIN\BOOTLD.SYM

NUMBUFF EQU $F0B7

DEVI2C EQU $70


ORG $E000
JP START2

		;----LCD 16x2 via i2c
		@LCDCX DEFS 1 							;DISPLAY X POS (0..F  FOR 1..16)
		@LCDCY DEFS 1 							;DISPLAY Y POS (0 OR 1 FOR LINE 1 AND 2)
		@LCD_DSPCTRL DEFS 1 						;LCD I2C 16X2
		@LCD_DSPMODE DEFS 1 						;LCD I2C 16X2
		@LCD_STSMASK DEFS 1 						;LCD I2C 16X2		
		@BUFFER DEFS 20 						; 20 BYTE BUFFER FOR I2C USAGE		
		@MYNUM DEFS 13 							;10CHARS MESSAGE FOR NUMBER AND 3 TERMINATED
		;@B2DBUF DEFS 20 						;ASCCI STRING OF THE NUMBER
		@B2DEND DEFS 1 							;0 FOR TERMINATE THE STRING								
		;----I2C DS1307 MODULE
		@TIMMSG DEFS 20							;BUFFER FOR DS1307 TIME I2C			
		@FOUND_DEVICES_BUFFER DEFS 10


@SOUTAS:	PUSH HL
		PUSH BC
		PUSH DE
		PUSH AF 							;SERIAL PRINT ASCII IN DECIMAL
		LD H, 0
		LD L, A
		LD DE, MYNUM
		CALL OUTASC
		
		LD A, 10
		LD (DE), A
		INC DE
		LD A, 13
		LD (DE), A
		INC DE
		XOR A
		LD (DE), A
		
		LD HL, MYNUM
		CALL RS_TXT
		POP AF
		POP DE	
		POP BC
		POP HL
		RET

;A:THE NUMBER
;HL THE MESSAGE
@SPRN_MESNUM:   PUSH HL
		PUSH BC
		PUSH DE
		PUSH AF 
		
		PUSH AF
		CALL RS_TXT ;MESSAGE FIRST
		LD A, ' '
		CALL RS_TX
		
		LD HL, MYNUM
		LD A, '0'
		LD (HL),A
		INC HL
		LD A, 'x'
		LD (HL),A
		INC HL
		POP AF
		CALL StrfHex ;OUTASC
		XOR A
		LD (HL), A		
		LD HL, MYNUM
		CALL RS_TXT
		CALL RS_NEWLINE	
		
		POP AF
		POP DE	
		POP BC
		POP HL
		RET

@SPRN_NUMMES:   PUSH HL
		PUSH BC
		PUSH DE
		PUSH AF 
		
		PUSH HL		
		
		;CALL BN2BCD	;A THE NUMBER OUTPUT AT HL THE BCD NUMBER		
		CALL B2D8 	;B2DBUF HAS THE NUMBER TO PRINT AS ASCII TEXT
		LD HL,B2DBUF
		CALL SkipWhitespace
		CALL RS_TXT
		LD A, ' '
		CALL RS_TX
		LD HL, MYNUM
		CALL RS_TXT
		POP HL
		CALL RS_TXT ;MESSAGE 
		CALL RS_NEWLINE	
		
		POP AF
		POP DE	
		POP BC
		POP HL
		RET



