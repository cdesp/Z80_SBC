INCLUDE .\BIN\BOOTLD.SYM

NUMBUFF EQU $F0B7

;DEVI2C EQU $70


ORG $E000
JP START



INCLUDE ATL_I2C_LCD16X2.Z80
INCLUDE ATL_I2C_DS1307.Z80

DS1307_ADJUST_TST:	
;SET PARAMS
		LD DE, BUFFER
		XOR A
		LD (DE), A
		INC DE
		LD A, 1
		CALL BN2BCD
		LD A, L
		LD (DE), A
		INC DE
		LD A, 15
		CALL BN2BCD
		LD A, L
		LD (DE), A
		INC DE
		LD A, 9
		CALL BN2BCD
		LD A, L
		LD (DE), A
		INC DE
		LD A, 4
		LD (DE), A
		INC DE
		LD A, 2
		CALL BN2BCD
		LD A, L
		LD (DE), A
		INC DE
		LD A, 7
		CALL BN2BCD
		LD A, L
		LD (DE), A
		INC DE
		LD A, 26
		CALL BN2BCD
		LD A, L
		LD (DE), A
		INC DE
		XOR A
		LD (DE), A
		CALL DS1307_ADJUST
		RET

;SCAN I2C AND REPORT DEVICES
START2: CALL RS_MESG
	DEFM 'SCANNING i2c'
	DB 10,13,0
	DEFM 'INIT i2c'
	DB 10,13,0
	CALL I2C_INIT
	CALL RS_MESG
	DEFM 'SCAN i2c'
	DB 10,13,0
	CALL I2C_SCAN
	LD HL,MES_DVFND
	CALL SPRN_NUMMES
	DEFM 'REPORT i2c'
	DB 10,13,0
	CALL I2C_REPORT
	JP BOOTMENU


MES_DVFND:	DEFM "I2C DEVICES FOUND"
	DB 0


START:	CALL RS_MESG
	DEFM 'TESTING i2c'
	DB 10,13,0

	JP DOLCD	

		;iNIT I2C
		CALL I2C_INIT

	CALL RS_MESG
	DEFM 'DS1307 INIT'
	DB 10,13,0
		CALL DS1307_INIT 						;
		LD HL, STR_I2C
		CALL RS_TXT
	CALL RS_MESG
	DEFM 'DS1307 SET TIME'
	DB 10,13,0
		CALL DS1307_ADJUST_TST 					;SET A DEFAULT DATETIME ON DS1307


DOLCD:	
	CALL RS_MESG
	DEFM 'LCD INIT'
	DB 10,13,0
		CALL LCD16_INIT 						;LCD 16x2 Initialized

		CALL LCD16_CLR
		LD HL, STR0
		CALL LCD16_PRINT
		LD HL, STR_LCD16
		CALL RS_TXT
		LD D,0
		LD E,1
		CALL LCD16_SETCURS
		LD HL, STR1
		CALL LCD16_PRINT	

		LD D,0
		LD E,2
		CALL LCD16_SETCURS
		LD HL, STR1
		CALL LCD16_PRINT

		LD D,0
		LD E,3
		CALL LCD16_SETCURS
		LD HL, STR1
		CALL LCD16_PRINT			
	
;	CALL DS1307_GETTIME
;	LD HL,TIMMSG
;	CALL RS_TXT


	JP BOOTMENU


	call printnum

    RET

STR_I2C	DEFM "I2C INITIALIZED"
	DB 10,13,0

STR0	DEFM "LCD INITIALIZED"
	DB 0
STR1	DEFM "CDESP 2026"
	DB 0

STR_LCD16 	DEFM "LCD 16x2 OK"
		DB 10,13,0	


