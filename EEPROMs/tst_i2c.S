INCLUDE .\BIN\BOOTLD.SYM

NUMBUFF EQU $F0B7

DEVI2C EQU $70


ORG $E000
JP START

		;----LCD 16x2 via i2c
		@LCDCX DEFS 1 							;DISPLAY X POS (0..F  FOR 1..16)
		@LCDCY DEFS 1 							;DISPLAY Y POS (0 OR 1 FOR LINE 1 AND 2)
		@LCD_DSPCTRL DEFS 1 						;LCD I2C 16X2
		@LCD_DSPMODE DEFS 1 						;LCD I2C 16X2
		@LCD_STSMASK DEFS 1 						;LCD I2C 16X2		
		@BUFFER DEFS 20 						; 20 BYTE BUFFER FOR I2C USAGE		
		@MYNUM DEFS 13 							;10CHARS MESSAGE FOR NUMBER AND 3 TERMINATED
		@B2DBUF DEFS 20 						;ASCCI STRING OF THE NUMBER
		@B2DEND DEFS 1 							;0 FOR TERMINATE THE STRING								
		;----I2C DS1307 MODULE
		@TIMMSG DEFS 20							;BUFFER FOR DS1307 TIME I2C			


@SOUTAS:	PUSH HL
		PUSH BC
		PUSH DE
		PUSH AF 							;SERIAL PRINT ASCII IN DECIMAL
		LD H, 0
		LD L, A
		LD DE, MYNUM
		CALL OUTASC
		
		LD A, 10
		LD (DE), A
		INC DE
		LD A, 13
		LD (DE), A
		INC DE
		XOR A
		LD (DE), A
		
		LD HL, MYNUM
		CALL RS_TXT
		POP AF
		POP DE	
		POP BC
		POP HL
		RET





INCLUDE ATL_I2C_FPGA.Z80
INCLUDE ..\..\MyModular\EEPROMs\ATL_I2C_LCD16X2.Z80
INCLUDE ..\..\MyModular\EEPROMs\ATL_I2C_DS1307.Z80

DS1307_ADJUST_TST:	
;SET PARAMS
		LD DE, BUFFER
		XOR A
		LD (DE), A
		INC DE
		LD A, 1
		CALL BN2BCD
		LD A, L
		LD (DE), A
		INC DE
		LD A, 15
		CALL BN2BCD
		LD A, L
		LD (DE), A
		INC DE
		LD A, 9
		CALL BN2BCD
		LD A, L
		LD (DE), A
		INC DE
		LD A, 4
		LD (DE), A
		INC DE
		LD A, 2
		CALL BN2BCD
		LD A, L
		LD (DE), A
		INC DE
		LD A, 7
		CALL BN2BCD
		LD A, L
		LD (DE), A
		INC DE
		LD A, 26
		CALL BN2BCD
		LD A, L
		LD (DE), A
		INC DE
		XOR A
		LD (DE), A
		CALL DS1307_ADJUST
		RET


START:	CALL RS_MESG
	DEFM 'TESTING i2c'
	DB 10,13,0
	

		;iNIT I2C
		CALL I2C_INIT

	CALL RS_MESG
	DEFM 'DS1307 INIT'
	DB 10,13,0
		CALL DS1307_INIT 						;
		LD HL, STR_I2C
		CALL RS_TXT
	CALL RS_MESG
	DEFM 'DS1307 SET TIME'
	DB 10,13,0
		CALL DS1307_ADJUST_TST 					;SET A DEFAULT DATETIME ON DS1307


	
	CALL RS_MESG
	DEFM 'LCD INIT'
	DB 10,13,0
		CALL LCD16_INIT 						;LCD 16x2 Initialized

		LD HL, STR0
		CALL LCD16_PRINT
		LD HL, STR_LCD16
		CALL RS_TXT
	
	CALL DS1307_GETTIME
	LD HL,TIMMSG
	CALL RS_TXT


	JP BOOTMENU


	call printnum

    RET

STR_I2C	DEFM "I2C INITIALIZED"
	DB 10,13,0

STR0	DEFM "LCD INITIALIZED"
	DB 0

STR_LCD16 	DEFM "LCD 16x2 OK"
		DB 10,13,0	


