SND_OUT2:
    ; --- ADD SETUP DELAY HERE ---
    PUSH AF        ; Save data
    LD B, 10       ; Small counter for a real delay
.wait: DJNZ .wait  ; Count down
    POP AF         ; Restore data
    ; --- END DELAY ---
    OUT (DEVSND), A
    RET

; Corrected Mute Routine
SND_MUTEALL2:
    LD A, $8F 
